#!/usr/bin/env python3
"""Build the Classic campaign from recovered stage data; does not execute Lua.

The stage order comes from profiles/classic_episode.json, which mirrors the
first page and supported prefix of the second page of Poached Eggs declared by the recovered episodes.lua.
"""
import argparse,json,math,tempfile
from pathlib import Path
from import_level import convert,ROOT,DEFAULT_PROFILE
from game_profiles import decode_payload
EPISODE=ROOT/'profiles/classic_episode.json'
STARS=ROOT/'profiles/star_limits.json'

# Power-ups of the shop tutorials (episodes.lua shopTutorialPowerup); codes shared with campaign_types.h.
POWERUPS={'kingsling':1,'slingscope':2,'birdquake':3,'powerpotion':4,'shockwave':5}

def star_limits(stars,script):
    """(silver, gold) from starLimits.lua; Golden Eggs stages have none (they give the egg), so any win is 3 stars."""
    v=stars.get(script);return (v['silver'],v['gold']) if v else (0,0)

def write_binary(levels,profile,polys,forced,stars,path=None):
    """CAMPAIGN.BIN: the stages read by the game at start-up (format in ps2/src/campaign_types.h)."""
    import struct
    r=lambda v:float(f'{v:.8f}')  # same rounding as the former C header
    strings=bytearray(b'\0');index={}
    def s(text):
        if text not in index:index[text]=len(strings);strings.extend(text.encode()+b'\0')
        return index[text]
    shapes=['box','circle','triangle_l','triangle_m','polygon'];objs=bytearray();joints=bytearray();lv=bytearray();no=nj=0
    for d in levels:
        o0,j0=no,nj
        for o in d['objects']:
            objs+=struct.pack('<8f2iI2fii',*[r(o[k]) for k in ['x','y','angle','width','height','density','strength','defence']],o['kind'],shapes.index(o['shape']),s(o['definition']),r(o['friction']),r(o['restitution']),o.get('spawn_of',0),(1 if o.get('no_collision') else 0)|o.get('mirror',0)|(8 if o.get('gun_bubble') else 0)|(16 if o.get('sucker') else 0)|(32 if o.get('cannon_ball') else 0)|(o.get('wave',0)<<26)|((o['release_bird']+1)<<8 if 'release_bird' in o else 0)|((o['clone_of']+1)<<16 if 'clone_of' in o else 0));no+=1
            objs+=struct.pack('<I',s(o['name'].split('_',1)[1] if o.get('wave') else ''))  # vehicle pieces: original name (getBlock)
        for j in d.get('joints') or []:
            joints+=struct.pack('<3i7fif6fi',j['type'],j['a'],j['b'],*[r(j[k]) for k in ['ax','ay','bx','by','frequency','damping','break_force']],int(j['collide']),r(j.get('destroy_timer',0.0)),*[r(j.get(k,0.0)) for k in ['axis_x','axis_y','lower','upper','motor_speed','max_force']],(1 if j.get('limit') else 0)|(2 if j.get('motor') else 0)|(4 if j.get('back_and_forth') else 0));nj+=1
            joints+=struct.pack('<I',s(j['name'] if j.get('vehicle') else ''))  # vehicle joints: original name (removeJoint)
        types=[b['type'] for b in d['birds']];types+=[0]*(16-len(types))
        lv+=struct.pack('<3I16i8f2Ii2I2ii',o0,len(d['objects']),len(d['birds']),*types,*map(r,[d['gravity'],d['sling_x'],d['sling_y'],d['ground_y'],d['physics_to_world'],d['view']['x'],d['view']['y'],d['view']['scale']]),s(d['title']),s(d['stage_script']),d.get('texture_bank',0),j0,nj-j0,*star_limits(stars,d['stage_script']),POWERUPS.get(d.get('powerup',''),0))
    pol=bytearray()
    for name in polys:
        v=[c for xy in profile['objects'][name]['vertices'] for c in xy];pol+=struct.pack('<Ii16f',s(name),len(v)//2,*map(r,v+[0.0]*(16-len(v))))
    frc=bytearray()
    # Per-definition record: constant force (forceX/forceY, targetVelocity) and explosion
    # (explosionRadius, explosionForce, explosionDamageRadius, explosionDamage) from blocks.lua, and the
    # Short Fuse vial (1 orange, 2 pink, 3 blue; vialEffect.radius), and the Egg Defender thrust
    # (forceRelative, targetVelocity, applyForceInterval; flag 1 = starts powered off, disableForce).
    for name in forced:
        spec=profile['objects'][name];th=spec.get('thrust',{})
        frc+=struct.pack('<I7fif3fi',s(name),*map(r,spec.get('force',[0.0,0.0])),r(spec.get('force_target',0.0)),*map(r,spec.get('explosion',[0.0,0.0,0.0,0.0])),int(spec.get('vial',[0,0.0])[0]),r(spec.get('vial',[0,0.0])[1]),
                         r(th.get('force',0.0)),r(th.get('target',0.0)),r(th.get('interval',0.0)),1 if th.get('off') else 0)
    while len(strings)%4:strings.append(0)
    head=struct.pack('<4s7I',b'PBCP',7,len(levels),no,nj,len(polys),len(forced),len(strings))
    data=head+bytes(lv)+bytes(objs)+bytes(joints)+bytes(pol)+bytes(frc)+bytes(strings)
    (Path(path) if path else ROOT/'ps2/assets/CAMPAIGN.BIN').write_bytes(data)

def write_definition_sprites(profile=None):
    """ps2/src/definition_sprites.h: sprite of each piece added from blocks.lua (drawn by main.c)."""
    profile=profile or json.loads(Path(DEFAULT_PROFILE).read_text())
    from extract_sprites import HALF_RESOLUTION as HALF
    auto=sorted(k for k,v in profile['objects'].items() if v.get('auto'))
    (ROOT/'ps2/src/definition_sprites.h').write_text('/* Generated by tools/build_campaign.py: sprite of each piece added from blocks.lua. */\n#ifndef PS2BIRDS_DEFINITION_SPRITES_H\n#define PS2BIRDS_DEFINITION_SPRITES_H\ntypedef struct {const char *definition;int sprite,scale;} DefinitionSprite;\nstatic const DefinitionSprite definition_sprites[]={\n'+''.join(' {"%s",SPR_%s,%d},\n'%(k,profile['objects'][k]['sprite'],2 if (profile['objects'][k]['sprite'].startswith(HALF) or profile['objects'][k].get('half_resolution')) else 1) for k in auto)+' {0,0,0}};\n#endif\n')

def read_binary(path):
    """Parse CAMPAIGN.BIN back (tests and tools): levels, objects, joints, polygons, forces."""
    import struct
    d=Path(path).read_bytes();magic,ver,nl,no,nj,np,nf,ns=struct.unpack_from('<4s7I',d)
    if magic!=b'PBCP' or ver!=7:raise ValueError('Not a CAMPAIGN.BIN')
    p=32;strs=d[32+nl*140+no*64+nj*80+np*72+nf*56:]
    s=lambda o:strs[o:strs.index(b'\0',o)].decode()
    lv=[struct.unpack_from('<3I16i8f2Ii2I2ii',d,p+i*140) for i in range(nl)];p+=nl*140
    ob=[struct.unpack_from('<8f2iI2fiiI',d,p+i*64) for i in range(no)];p+=no*64
    jo=[struct.unpack_from('<3i7fif6fiI',d,p+i*80) for i in range(nj)];p+=nj*80
    po={};fo={};ex={};vi={};th={}
    for i in range(np):
        v=struct.unpack_from('<Ii16f',d,p+i*72);po[s(v[0])]=(v[1],list(v[2:2+2*v[1]]))
    p+=np*72
    for i in range(nf):
        v=struct.unpack_from('<I7fif3fi',d,p+i*56);fo[s(v[0])]=(v[1],v[2])
        if v[10] or v[13]:th[s(v[0])]=(v[10],v[11],v[12],v[13])
        if any(v[4:8]):ex[s(v[0])]=tuple(v[4:8])
        if v[8]:vi[s(v[0])]=(v[8],v[9])
    return {'levels':[{'title':s(l[27]),'script':s(l[28]),'objects':l[1],'birds':l[2],'bank':l[29],'joints':l[31],'powerup':l[34]} for l in lv],
            'objects':[{'definition':s(o[10]),'spawn_of':o[13],'no_collision':bool(o[14]&1),'mirror':o[14]&6,'gun_bubble':bool(o[14]&8),'sucker':bool(o[14]&16),'cannon_ball':bool(o[14]&32),'wave':(o[14]>>26)&15,'release_bird':((o[14]>>8)&255)-1,'clone_of':((o[14]>>16)&1023)-1,'name':s(o[15])} for o in ob],
            'joints':[{'type':j[0],'destroy_timer':j[11],'axis':(j[12],j[13]),'lower':j[14],'upper':j[15],'motor_speed':j[16],'max_force':j[17],'flags':j[18],'name':s(j[19])} for j in jo],'polygons':po,'forces':fo,'explosions':ex,'vials':vi,'thrust':th}

def build(episode_path=EPISODE,apk=None,workdir=None,output=None,quiet=False):
    """apk: read the stages straight from the APK (no decompiled files); workdir: where the stage JSON go."""
    episode=json.loads(Path(episode_path).read_text());levels=[];stars=json.loads(STARS.read_text())['limits']
    pages=[{'number':1,'title_prefix':episode['title_prefix'],'levels':episode['levels']}]+episode.get('additional_pages',[])
    entries=[(page,number,name) for page in pages for number,name in enumerate(page['levels'],1)]
    names=[entry[2] for entry in entries]
    if len(names)!=len(set(names)) or not 1<=len(names)<=1024:raise ValueError('Episode list must be 1..1024 unique stages')
    with tempfile.TemporaryDirectory(prefix='ps2birds-campaign-') as folder:
        for page,position,name in entries:
            apk_name=f'assets/data{page.get("folder",episode["folder"])}/{name}.lua'
            source=ROOT/f'ps2/data/{name}.decompiled.lua'
            if apk is not None:source=decode_payload(apk.read(apk_name),'classic')
            output_json=Path(workdir or ROOT/'ps2/data')/f'level_{page["number"]}_{position}.json'
            waves=None;bird_limit=None
            if name.startswith('EggDefender_') and not name.startswith('EggDefender_classic') and apk is not None:
                # EggDefender_N.scripts.lua: waves of vehicles and the bird limit (data only).
                from lua51_data import load as _load
                script=_load(decode_payload(apk.read(apk_name[:-4]+'.scripts.lua'),'classic'));bird_limit=int(script['birdLimit']);waves=[]
                for _,wave in sorted(script['waves'].items()):
                    egg=json.loads((ROOT/'profiles/egg_defender.json').read_text());snap=set(egg['no_ground_snap']);stay=set(egg['no_teleport'])
                    for _,v in sorted(wave.items()):waves.append((float(v['x']),float(v['y']),_load(decode_payload(apk.read('assets/data/vehicles/'+v['type']+'.lua'),'classic')),v['type'].split('/')[-1] not in snap,v['type'].split('/')[-1] in stay))
            convert(source,output_json,Path(folder)/'level_data.h',DEFAULT_PROFILE,apk_name,quiet,waves)
            d=json.loads(output_json.read_text());
            if bird_limit:d['birds']=[dict(d['birds'][0],definition='RedBird',type=0) for _ in range(bird_limit)];d['egg_defender']=True
            d['title']=f'{page["title_prefix"]}{position+page.get("first",1)-1}';d['stage_script']=name;d['episode_page']=page['number'];d['powerup']=episode.get('powerups',{}).get(name,'');d['stage_number']=position;d['texture_bank']=page.get('bank',0)
            if name!='Level1':
                left=d['sling_x']-4;right=d['sling_x']+4;top=d['sling_y']-5
                for o in d['objects']:
                    cs=abs(math.cos(o['angle']));sn=abs(math.sin(o['angle']))
                    ex=(o['width']*cs+o['height']*sn)/2;ey=(o['width']*sn+o['height']*cs)/2
                    left=min(left,o['x']-ex);right=max(right,o['x']+ex);top=min(top,o['y']-ey)
                if d.get('egg_defender'):  # the original camera: one screen from the slingshot (EGG_SCREEN)
                    from import_level import EGG_SCREEN,EGG_MARGIN
                    left=d['sling_x']-EGG_MARGIN;right=left+EGG_SCREEN
                scale=min(7,576/(right-left),210/max(1,d['ground_y']-top))
                d['view']={'scale':scale,'x':32-left*scale,'y':368-d['ground_y']*scale}
            output_json.write_text(json.dumps(d,indent=2)+'\n');levels.append(d)
    def f(value):return f'{value:.8f}f'
    lines=['/* Generated by tools/build_campaign.py from recovered Classic data. */','#ifndef PS2BIRDS_CAMPAIGN_DATA_H','#define PS2BIRDS_CAMPAIGN_DATA_H','#include "campaign_types.h"']
    for i,d in enumerate(levels):
        lines.append(f'static const CampaignObject campaign_objects_{i}[] = {{')
        for o in d['objects']:
            values=[o[k] for k in ['x','y','angle','width','height','density','strength','defence']]
            lines.append(' {'+','.join(f(v) for v in values)+','+str(o['kind'])+','+str(['box','circle','triangle_l','triangle_m','polygon'].index(o['shape']))+','+json.dumps(o['definition'])+','+f(o['friction'])+','+f(o['restitution'])+'},')
        lines.append('};')
    for i,d in enumerate(levels):
        if d.get('joints'):
            lines.append(f'static const CampaignJoint campaign_joints_{i}[] = {{')
            for j in d['joints']:
                lines.append(' {'+','.join(str(j[k]) for k in ['type','a','b'])+','+','.join(f(j[k]) for k in ['ax','ay','bx','by','frequency','damping','break_force'])+','+str(int(j['collide']))+','+f(j.get('destroy_timer',0.0))+'}, /* '+j['name']+' */')
            lines.append('};')
    # Polygon shapes (blocks.lua "vertices", fractions of the sprite box), looked up by definition.
    profile=json.loads(Path(DEFAULT_PROFILE).read_text())
    polys=sorted({o['definition'] for d in levels for o in d['objects'] if o['shape']=='polygon'})
    lines.append('static const CampaignPolygon campaign_polygons[] = {')
    for name in polys:
        v=profile['objects'][name]['vertices']
        if not 3<=len(v)<=8:raise ValueError('Polygon needs 3..8 vertices: '+name)
        lines.append(' {'+json.dumps(name)+','+str(len(v))+',{'+','.join(f(c) for xy in v for c in xy)+'}},')
    lines.append(' {0,0,{0}}};')
    # Constant forces of balloon-like materials (forceX/forceY), looked up by definition.
    forced=sorted({o['definition'] for d in levels for o in d['objects'] if 'force' in profile['objects'][o['definition']] or 'explosion' in profile['objects'][o['definition']] or 'vial' in profile['objects'][o['definition']] or 'thrust' in profile['objects'][o['definition']]})
    lines.append('static const CampaignForce campaign_forces[] = {')
    for name in forced:fx,fy=profile['objects'][name].get('force',[0.0,0.0]);lines.append(' {'+json.dumps(name)+','+f(fx)+','+f(fy)+'},')
    lines.append(' {0,0,0}};')
    lines.append('static const CampaignLevel campaign_levels[] = {')
    for i,d in enumerate(levels):
        values=[d['gravity'],d['sling_x'],d['sling_y'],d['ground_y'],d['physics_to_world'],d['view']['x'],d['view']['y'],d['view']['scale']]
        lines.append(' {campaign_objects_'+str(i)+','+str(len(d['objects']))+','+str(len(d['birds']))+',{'+','.join(str(b['type']) for b in d['birds'])+'},'+','.join(f(v) for v in values)+','+json.dumps(d['title'])+','+json.dumps(d['stage_script'])+','+str(d.get('texture_bank',0))+','+(f'campaign_joints_{i},{len(d["joints"])}' if d.get('joints') else '0,0')+','+','.join(map(str,star_limits(stars,d['stage_script'])))+'},')
    write_binary(levels,profile,polys,forced,stars,output)
    # Sprites of the pieces added by tools/add_definitions.py, drawn by ps2/src/main.c.
    auto=sorted(k for k,v in profile['objects'].items() if v.get('auto'))
    if apk is None:write_definition_sprites(profile)
    print(f'CAMPAIGN.BIN: {len(levels)} stages')
if __name__=='__main__':build()
